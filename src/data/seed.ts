function rating(score: number): "low" | "medium" | "high" | "critical" {
  if (score >= 17) return "critical";
  if (score >= 10) return "high";
  if (score >= 5) return "medium";
  return "low";
}

function mkRisk(
  seed: Partial<Risk> & {
    id: string;
    risk_title: string;
    risk_category: Risk["risk_category"];
    likelihood: number;
    impact: number;
    residual_likelihood: number;
    residual_impact: number;
  },
): Risk {
  const iScore = seed.likelihood * seed.impact;
  const rScore = seed.residual_likelihood * seed.residual_impact;
  return {
    id: seed.id,
    business_id: BUSINESS_ID,
    risk_title: seed.risk_title,
    risk_category: seed.risk_category,
    description: seed.description ?? "",
    cause: seed.cause ?? "",
    consequence: seed.consequence ?? "",
    likelihood: seed.likelihood,
    impact: seed.impact,
    inherent_score: iScore,
    inherent_rating: rating(iScore),
    controls: seed.controls ?? "",
    control_effectiveness: seed.control_effectiveness ?? "adequate",
    residual_likelihood: seed.residual_likelihood,
    residual_impact: seed.residual_impact,
    residual_score: rScore,
    residual_rating: rating(rScore),
    risk_owner: seed.risk_owner ?? "Anastasia",
    response: seed.response ?? "reduce",
    mitigation_actions: seed.mitigation_actions ?? [],
    status: seed.status ?? "open",
    review_date: seed.review_date ?? daysFrom(90),
    accepted_at: seed.accepted_at ?? null,
    closed_at: seed.closed_at ?? null,
    acceptance_reason: seed.acceptance_reason,
    closure_reason: seed.closure_reason,
    linked_contract_id: seed.linked_contract_id ?? null,
    linked_entity_id: seed.linked_entity_id ?? null,
    linked_employee_id: seed.linked_employee_id ?? null,
    linked_obligation_id: seed.linked_obligation_id ?? null,
    linked_processing_activity_id: seed.linked_processing_activity_id ?? null,
    linked_governance_record_id: seed.linked_governance_record_id ?? null,
    created_at: seed.created_at ?? daysFrom(-90),
    updated_at: seed.updated_at ?? daysFrom(-10),
  };
}

